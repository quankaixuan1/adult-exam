// Each cloud function and the mini program are deployed independently.
const { copyFileSync, readFileSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const root = resolve(__dirname, '..');
for (const target of ['cloudfunctions/admin-api', 'cloudfunctions/student-api', 'admin/src/services']) {
  copyFileSync(resolve(root, 'shared/registration-schema.json'), resolve(root, target, 'registration-schema.json'));
}

// The mini program runtime loads JavaScript modules rather than JSON via require.
const schema = JSON.parse(readFileSync(resolve(root, 'shared/registration-schema.json'), 'utf8'));
writeFileSync(resolve(root, 'miniprogram/data/registration-schema.js'),
  '// Generated by scripts/sync-registration-schema.js. Do not edit directly.\nmodule.exports = ' + JSON.stringify(schema, null, 2) + ';\n');
